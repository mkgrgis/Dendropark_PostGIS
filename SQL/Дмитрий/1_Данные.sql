-- Список номеров маточных площадок
-- drop view "Бирюлёвский дендропарк: Дмитрий"."№№ пл. по экспликациии";
create view "Бирюлёвский дендропарк: Дмитрий"."№№ пл. по экспликациии" AS
select distinct "Уч.",
       "№₀",
       "№",
       "Адрес"
 from "Бирюлёвский дендропарк: Дмитрий"."Экспликация" e
where "Адрес" is not null
order by "Уч." asc, "№₀" asc;
