create or replace view "Бирюлёвский дендропарк"."№№ пл. сводка адресов" as
with w as (
select true wiki,
       "Уч." "Уч. w",
       "№"::text "№ w",
       "Адрес"
  from "Бирюлёвский дендропарк: Википедия"."№№ пл. по Википедии"
),
p as (
select true "ОКН",
       "Уч." "Уч. ОКН",
       "№"::text "№ ОКН",
       replace("Адрес", ' ', '') "Адрес"
  from "Бирюлёвский дендропарк: ОКН"."№№ пл. по паспорту ОКН"
),
o as (
select distinct true "ОСМ",
       "Уч." "Уч. ОСМ",
       "№" "ref OSM",
       "ref" "№ ОСМ",
       "из ОКН",
       "объектов OSM",
       "Уч." || '×' || "ref" || case when ref0 is not null then '(' || ref0 || ')' else '' end "Адрес",
       case when "объектов OSM" = 1 then "URL" else null end "URL"
  from "Бирюлёвский дендропарк: OSM"."№№ пл. по ОСМ" s
-- where s."из ОКН"
),
d as (
select true "каталог Дмитрия",
       "Уч." "Уч. Дм", "№сортировочный", "№" "№_ Дм", coalesce(s."Адрес", e."Адрес") "Адрес"
  from "Бирюлёвский дендропарк: Дмитрий"."№№ пл. по экспликациии" e
  left join ( -- Доопределение старых обозначений маточных площадок, Дмитрий таких сведений не публикует
    select "Адрес",
           split_part("Адрес", '(', 1) "Сокр"
      from "Бирюлёвский дендропарк: ОКН"."№№ пл. по паспорту ОКН" o
     where o."Адрес" ~'\('
            ) s
     on s."Сокр" = e."Адрес"
),
t as (
select distinct
       true "каталог табличек",
       "Адрес", "Уч." "Уч. т", "№_" "№ т", "№" "№_ т"
  from "Бирюлёвский дендропарк: Википедия"."Флористические таблички"
 where "№" is not null
)
select *
  from w
  full outer join p
 using ("Адрес")
  full outer join o
 using ("Адрес")
  full outer join d
 using ("Адрес")
  full outer join t
 using ("Адрес")
 order by d. "Адрес";

