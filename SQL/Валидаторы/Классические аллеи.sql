-- Представленность аллей в источниках
create view "Бирюлёвский дендропарк"."Кл. аллеи сводка" as
select ok."Объект Q",
       ok."№ в ОКН",
       ok."Объект" "Назв Викиданные",
       d."№ строки" is not null "Дм",
       aw.geom is not null "OSM алл",
       ao.geom is not null "OSM обс",
       a97."№" is not null "1997",
       wp."№" is not null "Википедия"
  from "Бирюлёвский дендропарк: WikiData"."Аллеи ОКН" ok
 inner join "Бирюлёвский дендропарк: Дмитрий"."ДТС" d
    on ok."Объект Q" = d."Q"
 inner join "Бирюлёвский дендропарк: OSM"."ДТС Wikidata" aw
    on aw."Q" = ok."Объект Q"
  left join "Бирюлёвский дендропарк: OSM"."Обсадки аллей Wikidata" ao
    on ao."Q" = ok."Объект Q"
  left join "Бирюлёвский дендропарк: проект 1997"."Характеристика аллей в дпарке" a97
    on a97.wikidata = ok."Объект Q"
  left join "Бирюлёвский дендропарк: Википедия"."Аллеи" wp
    on ok."№ в ОКН" = wp."№ в ОКН"
  order by ok."№ в ОКН" :: semver

