refresh materialized view "Бирюлёвский дендропарк: Википедия"."Ценные видовые раскрытия";

-- Ценные видовые раскрытия, представленнные во всех источниках
select "№",
       w."Название" = o."Название" "Назв eq",
       w.азимут = o."α₀" "α eq",
       o.α = w.α "диапазон eq",
       w."URL OSM" = o."OSM URL" "OSM URL eq",
       o."OSM URL",
       w.азимут,
       o."α₀",
       w."Название" "назв Википедия",
       o."Название" "назв OSM",
       o.α "OSM α", w.α "ВП α"
  from "Бирюлёвский дендропарк: Википедия"."Ценные видовые раскрытия" w
  full outer join "Бирюлёвский дендропарк: OSM"."Видовые точки" o
 using ("№")
 where w."Название" is not null
   and o."Название" is not null
   and w."Название" = o."Название" --Идентично представлены
   and w.азимут = o."α₀"
   and o.α = w.α
   and w."URL OSM" = o."OSM URL"
;

-- Иные видовые точки
select "№",
       w."Название" = o."Название" "Назв eq",
       w.азимут = o."α₀" "α eq",
       o.α = w.α "диапазон eq",
       w."URL OSM" = o."OSM URL" "OSM URL eq",
       o."OSM URL",
       w.азимут,
       o."α₀",
       w."Название" "назв Википедия",
       o."Название" "назв OSM",
       o.α "OSM α", w.α "ВП α"
  from "Бирюлёвский дендропарк: Википедия"."Ценные видовые раскрытия" w
  full outer join "Бирюлёвский дендропарк: OSM"."Видовые точки" o
 using ("№")
 where not (w."Название" is not null
   and o."Название" is not null
   and w."Название" = o."Название" --Идентично представлены
   and w.азимут = o."α₀"
   and o.α = w.α
   and w."URL OSM" = o."OSM URL")
;

